import torch


def grad_norm(params):
    """Global L2 norm of the gradients of ``params`` (parameters without a gradient are skipped)."""
    grad_norm = 0.
    for p in params:
        if p.grad is not None:
            grad_norm += torch.sum(p.grad ** 2)
    return torch.sqrt(grad_norm)
