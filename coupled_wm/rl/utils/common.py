import os
import random

import numpy as np
import torch


def seeding(seed=0):
    """Seed python, numpy and torch (CPU and every CUDA device); cuDNN autotuning stays on."""
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    os.environ['PYTHONHASHSEED'] = str(seed)
    torch.cuda.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)
    torch.backends.cudnn.benchmark = True
    torch.backends.cudnn.deterministic = False
    return seed
